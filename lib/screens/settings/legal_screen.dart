import 'package:flutter/material.dart';

import '../../core/theme.dart';
import '../../widgets/common.dart';

/// FR-5.5 — Privacy Policy and Terms of Service.
class LegalScreen extends StatelessWidget {
  const LegalScreen({super.key, required this.privacy});
  final bool privacy;

  static const _privacy = <(String, String)>[
    ('What we collect', 'Your email address and username for your account, and your study data: uploaded module summaries (key points), quiz results, coins, XP, inventory, garden state and preferences.'),
    ('Your study files', 'Files you upload are read on your phone only. Study Flora extracts the text to build key points and quizzes; the original file is not uploaded. Only the generated summary and a file fingerprint (to prevent duplicate rewards) are stored.'),
    ('Cloud backup', 'When you are signed in and online, your progress is backed up to Supabase so you can restore it on another device. Access is protected so that you can only read your own data.'),
    ('Offline use', 'Core study and garden features work offline. Changes are kept on your phone and synced when you reconnect. Unsynced data may be lost if app data is cleared.'),
    ('Your choices', 'You can edit your username, log out at any time, and contact the developers to delete your account and cloud data.'),
  ];

  static const _terms = <(String, String)>[
    ('Purpose', 'Study Flora is a study companion for students everywhere. Rewards (coins, XP, seeds, borders and badges) are virtual, have no monetary value, and cannot be exchanged.'),
    ('Fair play', 'Upload real study materials. Upload rewards are given once per unique file; attempts to farm rewards with duplicate or filler files are not eligible.'),
    ('Content', 'You are responsible for the files you upload. Do not upload content you do not have the right to use.'),
    ('Accuracy', 'Key points and quizzes are generated by rule-based text analysis and may contain mistakes. Always review with your official course materials.'),
    ('Changes', 'Features and game rules may be updated to improve the app. Continued use means you accept the updated terms.'),
  ];

  @override
  Widget build(BuildContext context) {
    final c = context.sf;
    final items = privacy ? _privacy : _terms;
    return Scaffold(
      appBar: AppBar(
        backgroundColor: c.bg,
        surfaceTintColor: Colors.transparent,
        title: Text(privacy ? 'Privacy Policy' : 'Terms of Service', style: context.tt.titleMedium),
      ),
      body: ListView(
        padding: const EdgeInsets.fromLTRB(16, 4, 16, 28),
        children: [
          SfCard(
            color: c.surfaceAlt,
            child: Row(children: [
              IconTile(privacy ? Icons.shield_outlined : Icons.fact_check_outlined, size: 48, bg: c.brandSoft),
              const SizedBox(width: 12),
              Expanded(
                child: Text(
                  privacy ? 'Learn how Study Flora protects your data.' : 'Our commitment to you, and what we ask in return.',
                  style: context.tt.titleSmall,
                ),
              ),
            ]),
          ),
          const SizedBox(height: 12),
          for (final (i, (title, body)) in items.indexed)
            Padding(
              padding: const EdgeInsets.only(bottom: 10),
              child: SfCard(
                child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                  Text('${i + 1}. $title', style: context.tt.titleSmall),
                  const SizedBox(height: 6),
                  Text(body, style: context.tt.bodyMedium?.copyWith(color: c.muted)),
                ]),
              ),
            ),
          Center(child: Text('Last updated: November 2026', style: context.tt.bodySmall)),
        ],
      ),
    );
  }
}
